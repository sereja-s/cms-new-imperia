<?php

namespace Imperia\Core;

/**
 * MODULE CONTRACT
 *
 * Базовый контракт всех модулей системы.
 *
 * Гарантирует, что каждый модуль:
 * - имеет точку входа init()
 * - может быть безопасно загружен ModuleManager'ом
 *
 * Вся архитектура модулей строится вокруг этого интерфейса.
 */
interface ModuleInterface
{
	/**
	 * Точка инициализации модуля.
	 *
	 * Вызывается один раз при загрузке системы.
	 * Здесь модуль должен регистрировать:
	 * - hooks (add_action / add_filter)
	 * - сервисы
	 * - внутреннюю логику
	 */
	public function init(): void;
}
