<?php

namespace Imperia\Core;

/**
 * ==========================================================
 * MODULE CONTRACT
 * ==========================================================
 *
 * Каждый модуль обязан иметь
 * единую точку инициализации.
 *
 * ВАЖНО:
 * init() должен только регистрировать:
 *
 * - add_action(...)
 * - add_filter(...)
 * - зависимости
 *
 * Запрещено:
 * - выполнять запросы к БД
 * - выполнять тяжёлые вычисления
 * - обращаться к внешним API
 * - выполнять бизнес-логику
 *
 * Реальная работа должна запускаться
 * только через WordPress hooks.
 */
interface ModuleInterface
{
	public function init(): void;
}
