<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Infrastructure;

/**
 * ==========================================================
 * MappingKeys
 * ==========================================================
 *
 * Централизованное хранилище ключей соответствий (mapping),
 * используемых модулем EDI.
 *
 * -----------------------------------------------------------------
 * Зачем нужен этот класс
 * -----------------------------------------------------------------
 *
 * Оригинальный плагин EDI использует строки вида:
 *
 *      _edi_1c_category_map
 *      _edi_1c_product_map
 *      ...
 *
 * непосредственно в коде.
 *
 * Такой подход неудобен:
 *
 * • строковые литералы начинают дублироваться;
 * • легко допустить опечатку;
 * • сложно изменить название ключа сразу во всём проекте.
 *
 * В Imperia Core все подобные ключи собраны
 * в одном месте.
 *
 * -----------------------------------------------------------------
 * Совместимость с EDI
 * -----------------------------------------------------------------
 *
 * Значения констант полностью совпадают
 * с оригинальными ключами плагина EDI.
 *
 * Благодаря этому:
 *
 * ✔ продолжаем использовать существующую базу данных EDI;
 *
 * ✔ не требуется миграция данных;
 *
 * ✔ совместимость сохраняется на 100%.
 *
 * -----------------------------------------------------------------
 * Правило
 * -----------------------------------------------------------------
 *
 * Во всём модуле запрещается писать строки
 * вида "_edi_1c_category_map".
 *
 * Используется только:
 *
 *      MappingKeys::CATEGORY
 *
 * Это значительно облегчает сопровождение проекта.
 */
final class MappingKeys
{
	/**
	 * ======================================================
	 * Соответствие GUID категории ↔ ID категории WooCommerce.
	 * ======================================================
	 *
	 * Используется:
	 *
	 *      Utils::get_guid_id_match()
	 *
	 *      Utils::set_guid_id_match()
	 *
	 * Полностью совместимо
	 * с оригинальным плагином EDI.
	 */
	public const CATEGORY = '_edi_1c_category_map';

	/**
	 * ======================================================
	 * Соответствие GUID товара ↔ ID товара WooCommerce.
	 * ======================================================
	 *
	 * Пока ещё не используется,
	 * но понадобится после переноса ProductParser.
	 */
	public const PRODUCT = '_edi_1c_product_map';

	/**
	 * ======================================================
	 * Запрещаем создание экземпляров класса.
	 * ======================================================
	 *
	 * Это справочник констант.
	 */
	private function __construct() {}
}
