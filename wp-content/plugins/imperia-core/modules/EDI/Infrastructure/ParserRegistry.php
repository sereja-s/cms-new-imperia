<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Infrastructure;

use BytePerfect\EDI\Parsers\CategoriesParser as BaseCategoriesParser;
use Imperia\Modules\EDI\Parsers\CategoriesParser;

/**
 * ==========================================================
 * ParserRegistry
 * ==========================================================
 *
 * Реестр замен штатных парсеров EDI.
 *
 * Сам плагин EDI при запуске формирует список парсеров
 * CommerceML и передаёт его через фильтр:
 *
 *      edi_register_import_parsers
 *
 * Imperia Core не изменяет механизм работы EDI,
 * а лишь заменяет необходимые парсеры
 * своими расширенными реализациями.
 *
 * Благодаря этому:
 *
 * • максимально используется существующая логика EDI;
 * • не приходится переписывать весь механизм импорта;
 * • можно заменить только нужные классы;
 * • остальные парсеры продолжают работать без изменений.
 *
 * В этом классе отсутствует бизнес-логика.
 *
 * Он знает только одно:
 *
 *      какой штатный класс
 *              ↓
 *      заменить каким собственным.
 */
final class ParserRegistry
{
	/**
	 * ======================================================
	 * Карта замен парсеров.
	 * ======================================================
	 *
	 * Ключ   — оригинальный класс EDI.
	 * Значение — собственная реализация Imperia Core.
	 *
	 * Постепенно сюда будут добавляться новые парсеры,
	 * например:
	 *
	 * ProductsParser
	 * OffersParser
	 * ProductImagesParser
	 * OrdersParser
	 * DocumentsParser
	 *
	 * При этом остальные парсеры EDI продолжат
	 * использоваться без изменений.
	 */
	private const MAP = [

		BaseCategoriesParser::class => CategoriesParser::class,

	];

	/**
	 * ======================================================
	 * Заменяет штатные парсеры EDI
	 * на собственные реализации.
	 * ======================================================
	 *
	 * Метод получает список всех парсеров,
	 * зарегистрированных EDI.
	 *
	 * Если для какого-либо класса существует запись
	 * в карте MAP,
	 * он заменяется нашей реализацией.
	 *
	 * Остальные элементы массива остаются без изменений.
	 *
	 * @param array $parsers
	 *      Список парсеров, зарегистрированных EDI.
	 *
	 * @return array
	 *      Обновлённый список парсеров.
	 */
	public function replace(array $parsers): array
	{
		foreach ($parsers as $index => $parser) {

			if (! isset(self::MAP[$parser])) {
				continue;
			}

			$parsers[$index] = self::MAP[$parser];
		}

		return $parsers;
	}
}
