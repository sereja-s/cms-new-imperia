<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Infrastructure;

/**
 * ==========================================================
 * StringNormalizer
 * ==========================================================
 *
 * Универсальный сервис нормализации строк.
 *
 * ----------------------------------------------------------
 * Зачем нужен этот класс
 * ----------------------------------------------------------
 *
 * Во многих местах модуля необходимо сравнивать строки,
 * полученные из различных источников:
 *
 * • названия дополнительных реквизитов 1С;
 * • названия характеристик;
 * • названия свойств;
 * • названия категорий;
 * • любые пользовательские строки.
 *
 * Простое сравнение через оператор === неудобно,
 * поскольку строки могут отличаться:
 *
 * • регистром;
 * • количеством пробелов;
 * • табуляцией;
 * • переводами строк;
 * • случайными пробелами в начале и конце.
 *
 * Чтобы не писать одинаковый код
 * в десятках различных классов,
 * вся логика вынесена сюда.
 *
 * Благодаря этому:
 *
 * ✔ код становится единообразным;
 *
 * ✔ любые изменения алгоритма выполняются
 *   только в одном месте;
 *
 * ✔ остальные сервисы вообще не знают,
 *   как именно выполняется сравнение строк.
 */
final class StringNormalizer
{
	/**
	 * Запрещаем создание экземпляров.
	 *
	 * Класс содержит только статические методы.
	 */
	private function __construct() {}

	/**
	 * ======================================================
	 * Нормализовать строку.
	 * ======================================================
	 *
	 * Выполняются следующие действия:
	 *
	 * 1. Удаляются пробелы по краям.
	 *
	 * 2. Любые последовательности пробелов,
	 *    табуляций и переводов строк
	 *    заменяются одним пробелом.
	 *
	 * 3. Строка переводится в нижний регистр
	 *    с поддержкой UTF-8.
	 *
	 * Пример:
	 *
	 *      "  АРТИКУЛ    ДЛЯ\tСАЙТА "
	 *
	 * превращается в
	 *
	 *      "артикул для сайта"
	 */
	public static function normalize(string $value): string
	{
		/*
         * Удаляем пробелы по краям.
         */
		$value = trim($value);

		/*
         * Любые пробельные символы
         * заменяем одним обычным пробелом.
         *
         * \s включает:
         *
         * • пробел;
         * • табуляцию;
         * • перевод строки;
         * • возврат каретки;
         * • другие пробельные символы Unicode.
         */
		$value = preg_replace('/\s+/u', ' ', $value) ?? '';

		/*
         * Переводим строку
         * в нижний регистр.
         */
		return mb_strtolower(
			$value,
			'UTF-8'
		);
	}

	/**
	 * ======================================================
	 * Сравнить две строки.
	 * ======================================================
	 *
	 * Перед сравнением обе строки
	 * проходят одинаковую нормализацию.
	 *
	 * Благодаря этому одинаковыми считаются:
	 *
	 * "Артикул для сайта"
	 *
	 * "АРТИКУЛ ДЛЯ САЙТА"
	 *
	 * " артикул   для   сайта "
	 *
	 * и т.д.
	 */
	public static function equals(
		string $left,
		string $right
	): bool {

		return self::normalize($left)
			=== self::normalize($right);
	}
}
