<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Parsers;

use BytePerfect\EDI\Parsers\DataXML;
use Exception;
use Imperia\Modules\EDI\Services\CategoryImportService;

/**
 * ==========================================================
 * CategoriesParser
 * ==========================================================
 *
 * Заменяет штатный CategoriesParser плагина EDI.
 *
 * ----------------------------------------------------------
 * Назначение
 * ----------------------------------------------------------
 *
 * Данный класс НЕ содержит бизнес-логики импорта.
 *
 * Он отвечает исключительно за:
 *
 * • получение события от EDI;
 * • чтение XML CommerceML;
 * • извлечение необходимых данных;
 * • передачу этих данных в сервис импорта.
 *
 * ----------------------------------------------------------
 * Почему именно так
 * ----------------------------------------------------------
 *
 * В оригинальном EDI данный класс одновременно:
 *
 * • читал XML;
 * • искал GUID;
 * • создавал категории;
 * • обновлял категории;
 * • сохранял GUID;
 * • формировал slug;
 * • работал с WooCommerce.
 *
 * Всё это нарушало принцип единственной ответственности.
 *
 * В Imperia Core вся бизнес-логика вынесена
 * в специализированные сервисы.
 *
 * Благодаря этому CategoriesParser остаётся
 * очень простым и удобным для сопровождения.
 */
final class CategoriesParser
{
	/**
	 * Сервис импорта категорий.
	 */
	private CategoryImportService $importService;

	/**
	 * ======================================================
	 * Конструктор.
	 * ======================================================
	 *
	 * Создаём сервис импорта
	 * и подписываемся
	 * на штатное событие EDI.
	 *
	 * Мы полностью используем механизм EDI,
	 * не меняя процесс разбора XML.
	 */
	public function __construct()
	{
		$this->importService = new CategoryImportService();

		add_action(
			'_/КоммерческаяИнформация/Классификатор/Категории/Категория',
			[$this, 'process']
		);
	}

	/**
	 * ======================================================
	 * Обработка одной категории CommerceML.
	 * ======================================================
	 *
	 * Метод вызывается автоматически EDI
	 * для каждой категории,
	 * найденной в import.xml.
	 *
	 * Здесь нет никакой бизнес-логики —
	 * только извлечение данных из XML.
	 */
	public function process(
		DataXML $xml
	): void {

		/*
         * Получаем массив,
         * сформированный DataXML.
         */

		$data = $xml->GetArray();

		/*
         * Извлекаем описание категории.
         */

		$category = $data['Категория']['#'];

		/*
         * GUID категории из 1С.
         */

		$guid = $category['Ид'][0]['#'];

		/*
         * Название категории.
         */

		$name = $category['Наименование'][0]['#'];

		/* imperia_log(
			sprintf(
				'CategoriesParser: processing "%s" (%s)',
				$name,
				$guid
			)
		); */

		/*
         * Передаём управление сервису импорта.
         */

		try {

			$this->importService->import(
				$guid,
				$name
			);
		} catch (Exception $exception) {

			/*
             * Логирование выполняем
             * через штатный механизм EDI,
             * чтобы все сообщения
             * попадали в общий журнал обмена.
             */

			imperia_log(
				sprintf(
					'CategoriesParser failed. GUID=%s. Error: %s',
					$guid,
					$exception->getMessage()
				)
			);
		}
	}
}
