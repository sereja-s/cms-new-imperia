<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Configuration;

use Imperia\Modules\EDI\Infrastructure\StringNormalizer;

/**
 * ==========================================================
 * AdditionalFieldNames
 * ==========================================================
 *
 * Централизованное хранилище названий
 * дополнительных реквизитов 1С,
 * используемых модулем EDI.
 *
 * ----------------------------------------------------------
 * Зачем нужен этот класс
 * ----------------------------------------------------------
 *
 * Вместо использования строковых литералов
 * непосредственно в коде:
 *
 *      "Артикул для сайта"
 *
 * используется:
 *
 *      AdditionalFieldNames::SITE_SKU
 *
 * Благодаря этому:
 *
 * ✔ отсутствует дублирование строк;
 *
 * ✔ исключаются опечатки;
 *
 * ✔ изменение названия выполняется
 *   только в одном месте.
 *
 * ----------------------------------------------------------
 * Важно
 * ----------------------------------------------------------
 *
 * Названия должны совпадать
 * с названиями дополнительных реквизитов,
 * созданных в базе 1С.
 *
 * Сравнение выполняется
 * без учёта регистра,
 * лишних пробелов,
 * табуляции
 * и переводов строк.
 */
final class AdditionalFieldNames
{
	/**
	 * Артикул для сайта.
	 */
	public const SITE_SKU = 'Артикул для сайта';

	/**
	 * Название для сайта.
	 */
	public const SITE_NAME = 'Название для сайта';

	/**
	 * Короткое описание.
	 */
	public const SHORT_DESCRIPTION = 'Короткое описание';

	/**
	 * Запрещаем создание экземпляров.
	 */
	private function __construct() {}

	/**
	 * ======================================================
	 * Проверить совпадение названия реквизита.
	 * ======================================================
	 *
	 * Используется вместо прямого сравнения строк.
	 *
	 * Например:
	 *
	 * if (
	 *     AdditionalFieldNames::equals(
	 *         $fieldName,
	 *         AdditionalFieldNames::SITE_SKU
	 *     )
	 * ) {
	 *     ...
	 * }
	 */
	public static function equals(
		string $fieldName,
		string $expectedName
	): bool {

		return StringNormalizer::equals(
			$fieldName,
			$expectedName
		);
	}
}
