<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI;

use Imperia\Core\ModuleInterface;
use Imperia\Modules\EDI\Hooks\RegisterHooks;

/**
 * ==========================================================
 * EDI MODULE
 * ==========================================================
 *
 * Модуль расширяет возможности плагина EDI.
 *
 * Сам обмен с 1С выполняет плагин EDI.
 *
 * Imperia Core НЕ заменяет EDI,
 * а подключает собственные Hooks,
 * расширяющие стандартную функциональность.
 *
 * Примеры:
 *
 * • сопоставление категорий по названию;
 * • использование "Названия для печати";
 * • поддержка "Артикула для сайта";
 * • исправление работы изображений;
 * • расширенный поиск;
 * • будущие доработки обмена.
 *
 * Здесь НЕ должно быть никакой бизнес-логики.
 * Module лишь запускает регистрацию Hooks.
 */
final class Module implements ModuleInterface
{
	/**
	 * Инициализация модуля.
	 */
	public function init(): void
	{
		new RegisterHooks();
	}
}
