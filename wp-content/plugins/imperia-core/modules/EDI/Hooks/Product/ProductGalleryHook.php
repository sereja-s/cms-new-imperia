<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Hooks\Product;

/**
 * ==========================================================
 * ProductGalleryHook
 * ==========================================================
 *
 * Данный класс изменяет стандартное поведение плагина EDI
 * при сохранении изображений товара.
 *
 * ----------------------------------------------------------
 * Зачем это нужно
 * ----------------------------------------------------------
 *
 * Стандартный алгоритм EDI работает так:
 *
 * Главная картинка
 *      ↓
 * image1
 *
 * Галерея
 *      ↓
 * image1
 * image2
 * image3
 * image4
 *
 * То есть первая картинка одновременно становится
 * главной и ещё раз попадает в галерею.
 *
 * WooCommerce умеет показывать главное изображение
 * отдельно, поэтому хранить его второй раз
 * в галерее нет никакого смысла.
 *
 * Мы хотим получить следующую схему:
 *
 * Главная картинка
 *      ↓
 * image1
 *
 * Галерея
 *      ↓
 * image2
 * image3
 * image4
 *
 * Самое приятное —
 * разработчик EDI специально предусмотрел
 * фильтр для изменения этого поведения.
 *
 * Поэтому никакой код EDI мы не копируем
 * и не заменяем.
 *
 * Мы лишь говорим EDI:
 *
 * "Удали первое изображение из массива галереи".
 */
final class ProductGalleryHook
{
	/**
	 * Регистрация фильтра.
	 */
	public function register(): void
	{
		add_filter(
			'edi_remove_first_image_from_gallery',
			[$this, 'removeFirstImage'],
			10,
			3
		);
	}

	/**
	 * Сообщает EDI,
	 * что первое изображение
	 * необходимо удалить
	 * из массива галереи.
	 *
	 * После этого сам EDI выполнит:
	 *
	 * array_shift($product_data['images']);
	 *
	 * и сохранит:
	 *
	 * image1 → главное изображение
	 *
	 * image2...
	 * → галерея.
	 *
	 * Мы ничего самостоятельно
	 * не изменяем.
	 *
	 * @param bool $remove
	 * @param \WC_Product $product
	 * @param array $productData
	 *
	 * @return bool
	 */
	public function removeFirstImage(
		bool $remove,
		\WC_Product $product,
		array $productData
	): bool {

		return true;
	}
}
