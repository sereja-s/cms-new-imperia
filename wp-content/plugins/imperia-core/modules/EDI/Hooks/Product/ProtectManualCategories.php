<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Hooks\Product;

use Imperia\Modules\EDI\Services\ManagedCategoryService;
use Imperia\Modules\EDI\Services\ProductCategoryMerger;
use Imperia\Modules\EDI\Services\ProductOwnership;
use WC_Product;

/**
 * ==========================================================
 * ProtectManualCategories
 * ==========================================================
 *
 * Защищает категории,
 * которые были добавлены администратором вручную.
 *
 * ----------------------------------------------------------
 * Почему появился этот класс
 * ----------------------------------------------------------
 *
 * Стандартный ProductCategoriesParser EDI
 * перед каждым сохранением выполняет:
 *
 *      $product->set_category_ids(...)
 *
 * То есть полностью заменяет список категорий
 * товара категориями, пришедшими из 1С.
 *
 * Если после обмена администратор добавил товару:
 *
 *      • Акция
 *      • Новинка
 *      • Хит продаж
 *
 * то при следующем обмене эти категории исчезают.
 *
 * ----------------------------------------------------------
 * Что делает данный Hook
 * ----------------------------------------------------------
 *
 * Перед сохранением товара:
 *
 * 1. Проверяет,
 *    находится ли товар уже под управлением обмена.
 *
 * 2. Если это первое сопоставление —
 *    НЕ вмешивается.
 *
 *    В этом случае EDI полностью назначает
 *    категории из 1С.
 *
 * 3. Если товар уже управляется обменом —
 *    сохраняет категории,
 *    добавленные администратором вручную.
 *
 * ----------------------------------------------------------
 * Почему первое сопоставление работает иначе
 * ----------------------------------------------------------
 *
 * До первого сопоставления товар
 * ещё не принадлежит обмену.
 *
 * Именно в этот момент происходит
 * принятие товара под управление.
 *
 * Поэтому категории должны стать
 * полностью такими,
 * как указано в 1С.
 *
 * Уже начиная со следующего обмена
 * ручные категории начинают защищаться.
 *
 * ----------------------------------------------------------
 * Архитектура
 * ----------------------------------------------------------
 *
 * Мы НЕ изменяем ProductCategoriesParser EDI.
 *
 * Используем штатную точку расширения:
 *
 *      edi_product_before_save
 *
 * Благодаря этому модуль Imperia Core
 * остаётся независимым от реализации EDI.
 */
final class ProtectManualCategories
{
	/**
	 * Определяет,
	 * какие категории принадлежат обмену.
	 */
	private ManagedCategoryService $managedCategories;

	/**
	 * Выполняет объединение категорий.
	 */
	private ProductCategoryMerger $merger;

	/**
	 * Определяет,
	 * находится ли товар
	 * под управлением обмена.
	 */
	private ProductOwnership $ownership;

	/**
	 * Конструктор.
	 */
	public function __construct()
	{
		$this->managedCategories = new ManagedCategoryService();

		$this->merger = new ProductCategoryMerger();

		$this->ownership = new ProductOwnership();
	}

	/**
	 * ======================================================
	 * Регистрация Hook.
	 * ======================================================
	 */
	public function register(): void
	{
		add_action(
			'edi_product_before_save',
			[$this, 'protect'],
			20,
			2
		);
	}

	/**
	 * ======================================================
	 * Защита ручных категорий.
	 * ======================================================
	 *
	 * Вызывается непосредственно
	 * перед сохранением товара EDI.
	 */
	public function protect(
		WC_Product $product,
		array &$productData
	): void {

		/*
         * Если категории вообще не переданы,
         * ничего делать не нужно.
         */
		if (!isset($productData['categories'])) {
			return;
		}

		/*
         * ==================================================
         * ВАЖНО
         * ==================================================
         *
         * Если товар ещё НЕ управляется обменом,
         * значит сейчас происходит первое
         * сопоставление.
         *
         * В этот момент НЕ вмешиваемся.
         *
         * Пусть EDI полностью назначит
         * категории из 1С.
         *
         * После записи GUID все следующие обмены
         * автоматически перейдут
         * в режим защиты ручных категорий.
         */
		if (!$this->ownership->isManaged($product)) {
			return;
		}

		/*
         * Получаем категории,
         * уже назначенные товару.
         */
		$currentCategories = $product->get_category_ids();

		/*
         * Определяем,
         * какие категории
         * принадлежат обмену.
         */
		$managedCategories = $this->managedCategories
			->getManagedCategories($product);

		/*
         * Получаем категории,
         * добавленные вручную.
         *
         * Это категории,
         * отсутствующие
         * среди управляемых обменом.
         */
		$manualCategories = array_diff(
			$currentCategories,
			$managedCategories
		);

		/*
         * Объединяем:
         *
         * категории из 1С
         *
         *        +
         *
         * ручные категории администратора.
         *
         * Категории обмена при этом
         * остаются полностью
         * под управлением 1С.
         */
		$productData['categories'] = $this->merger->merge(
			$productData['categories'],
			$manualCategories
		);

		/*
         * Диагностика.
         *
         * После завершения тестирования
         * можно удалить.
         */

		/*
        imperia_log(sprintf(
            'ProtectManualCategories: merged %d exchange categories with %d manual categories.',
            count($managedCategories),
            count($manualCategories)
        ));
        */
	}
}
