<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Hooks\Product;

/**
 * ==========================================================
 * DisablePendingStatus
 * ==========================================================
 *
 * Отключает штатное поведение EDI,
 * при котором перед полным обменом
 * все опубликованные товары переводятся
 * в статус "pending".
 *
 * ----------------------------------------------------------
 * Почему это необходимо
 * ----------------------------------------------------------
 *
 * По умолчанию EDI выполняет:
 *
 * UPDATE wp_posts
 * SET post_status = 'pending'
 * WHERE post_type = 'product'
 *   AND post_status = 'publish'
 *
 * После этого импорт постепенно
 * возвращает товары обратно в publish.
 *
 * На больших каталогах это приводит
 * к ситуации, когда некоторое время
 * все товары становятся недоступны
 * посетителям сайта.
 *
 * В нашем проекте используется
 * другой подход.
 *
 * Во время обмена изменяются
 * только те товары,
 * которые действительно пришли из 1С.
 *
 * Остальные товары должны оставаться
 * в своём текущем состоянии.
 *
 * ----------------------------------------------------------
 * Почему используется фильтр
 * ----------------------------------------------------------
 *
 * Разработчик EDI специально предусмотрел
 * возможность отключить данное поведение
 * через фильтр:
 *
 *      edi_should_mark_products_pending
 *
 * Поэтому мы не изменяем файлы EDI
 * и не переопределяем ImportXMLParser.
 *
 * Это полностью совместимо
 * с будущими обновлениями EDI.
 */
final class DisablePendingStatus
{
	/**
	 * Регистрирует фильтр.
	 */
	public function register(): void
	{
		add_filter(
			'edi_should_mark_products_pending',
			[$this, 'disable']
		);
	}

	/**
	 * ======================================================
	 * Запрещает массовый перевод товаров
	 * в статус "pending".
	 * ======================================================
	 *
	 * Метод вызывается EDI
	 * перед началом полного обмена.
	 *
	 * Возвращаем false,
	 * благодаря чему EDI пропускает
	 * выполнение массового UPDATE.
	 *
	 * Во время тестирования выводим
	 * диагностическое сообщение.
	 * После завершения тестов
	 * его можно удалить.
	 */
	public function disable(bool $enabled): bool
	{
		imperia_log(
			'DisablePendingStatus: skipping mass pending status update.'
		);

		return false;
	}
}
