<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Services;

use Imperia\Modules\EDI\Infrastructure\MappingKeys;
use WC_Product;

/**
 * ==========================================================
 * ProductOwnership
 * ==========================================================
 *
 * Определяет,
 * принадлежит ли товар обмену с 1С.
 *
 * ----------------------------------------------------------
 * Зачем нужен этот сервис
 * ----------------------------------------------------------
 *
 * До появления данного класса проверка выполнялась бы
 * непосредственно внутри каждого Hook.
 *
 * Например:
 *
 * if ( get_post_meta(...) )
 *
 * или
 *
 * if ( product has GUID )
 *
 * Но очень быстро подобный код начинает
 * копироваться во множество файлов.
 *
 * Поэтому вся логика определения владельца товара
 * вынесена в отдельный сервис.
 *
 * Теперь любые части Imperia Core могут просто спросить:
 *
 *      $ownership->isManaged($product);
 *
 * и получить ответ.
 *
 * ----------------------------------------------------------
 * Что считается "товаром обмена"
 * ----------------------------------------------------------
 *
 * Если у товара присутствует GUID,
 * сохранённый плагином EDI,
 * значит этот товар уже участвует в обмене.
 *
 * Если GUID отсутствует —
 * товар считается созданным вручную.
 *
 * Такой подход полностью соответствует логике,
 * реализованной разработчиком EDI.
 *
 * Мы ничего собственного не придумываем.
 *
 * ----------------------------------------------------------
 * Почему не проверяем SKU
 * ----------------------------------------------------------
 *
 * SKU используется исключительно
 * в момент первого сопоставления.
 *
 * После того как товар получил GUID,
 * именно GUID становится главным идентификатором.
 *
 * Поэтому дальнейшие проверки
 * всегда выполняются только по GUID.
 */
final class ProductOwnership
{
	/**
	 * ======================================================
	 * Проверить,
	 * управляется ли товар обменом.
	 * ======================================================
	 *
	 * Возвращает:
	 *
	 * TRUE
	 *      товар участвует в обмене.
	 *
	 * FALSE
	 *      товар создан вручную
	 *      и ещё никогда не сопоставлялся.
	 */
	public function isManaged(WC_Product $product): bool
	{
		return $this->getGuid($product) !== '';
	}

	/**
	 * ======================================================
	 * Проверить,
	 * является ли товар ручным.
	 * ======================================================
	 *
	 * Метод является логическим дополнением
	 * к isManaged().
	 *
	 * Благодаря этому код становится
	 * значительно более читаемым.
	 *
	 * Например:
	 *
	 * if ($ownership->isManual($product))
	 * {
	 *     ...
	 * }
	 */
	public function isManual(WC_Product $product): bool
	{
		return ! $this->isManaged($product);
	}

	/**
	 * ======================================================
	 * Получить GUID товара.
	 * ======================================================
	 *
	 * Используется внутренними методами.
	 *
	 * GUID хранится самим плагином EDI
	 * в стандартном метаполе.
	 *
	 * Мы не создаём никаких собственных полей,
	 * а используем уже существующую инфраструктуру.
	 */
	public function getGuid(WC_Product $product): string
	{
		$guid = (string) $product->get_meta(
			MappingKeys::PRODUCT,
			true
		);

		/*
     * --------------------------------------------------
     * Временная диагностика.
     *
     * Проверяем, какой GUID удалось прочитать.
     *
     * После завершения тестирования этот блок
     * можно удалить.
     * --------------------------------------------------
     */
		imperia_log(
			sprintf(
				'ProductOwnership: product #%d GUID = %s',
				$product->get_id(),
				$guid !== '' ? $guid : '[EMPTY]'
			)
		);

		return trim($guid);
	}
}
