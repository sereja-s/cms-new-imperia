<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Services;

/**
 * ==========================================================
 * ProductCategoryMerger
 * ==========================================================
 *
 * Сервис объединения категорий товара.
 *
 * ----------------------------------------------------------
 * Назначение
 * ----------------------------------------------------------
 *
 * Во время обмена с 1С необходимо сохранить
 * категории, добавленные администратором вручную.
 *
 * Пример.
 *
 * В 1С товар находится в категориях:
 *
 *      Ламинат
 *      Quick Step
 *
 * После импорта администратор вручную добавил:
 *
 *      Акция
 *      Хиты продаж
 *
 * При следующем обмене 1С пришлёт только:
 *
 *      Ламинат
 *      Quick Step
 *
 * Если просто выполнить:
 *
 *      set_category_ids(...)
 *
 * WooCommerce удалит категории:
 *
 *      Акция
 *      Хиты продаж
 *
 * Поэтому перед сохранением необходимо объединить:
 *
 *      категории из обмена
 *
 *                  +
 *
 *      категории администратора.
 *
 * ----------------------------------------------------------
 * Почему это отдельный сервис
 * ----------------------------------------------------------
 *
 * Этот класс ничего не знает:
 *
 * • о WooCommerce;
 * • о GUID;
 * • о CommerceML;
 * • о ProductParser;
 * • о хуках EDI.
 *
 * Он умеет только одно —
 * объединять два списка категорий.
 *
 * Благодаря этому сервис можно использовать
 * в любом месте проекта.
 */
final class ProductCategoryMerger
{
	/**
	 * ======================================================
	 * Объединить категории.
	 * ======================================================
	 *
	 * Первый массив —
	 * категории, пришедшие из обмена.
	 *
	 * Второй массив —
	 * категории, добавленные вручную.
	 *
	 * Если одинаковая категория присутствует
	 * в обоих списках,
	 * она останется только один раз.
	 *
	 * Порядок сохраняется:
	 *
	 * сначала категории обмена,
	 * затем ручные категории.
	 *
	 * ------------------------------------------------------
	 * Пример
	 * ------------------------------------------------------
	 *
	 * Exchange:
	 *
	 *      [5, 8]
	 *
	 * Manual:
	 *
	 *      [12, 15]
	 *
	 * Результат:
	 *
	 *      [5, 8, 12, 15]
	 *
	 * ------------------------------------------------------
	 *
	 * Exchange:
	 *
	 *      [5, 8]
	 *
	 * Manual:
	 *
	 *      [8, 12]
	 *
	 * Результат:
	 *
	 *      [5, 8, 12]
	 *
	 * ------------------------------------------------------
	 *
	 * @param int[] $exchangeCategories
	 * Категории, пришедшие из 1С.
	 *
	 * @param int[] $manualCategories
	 * Категории, добавленные вручную.
	 *
	 * @return int[]
	 * Итоговый список категорий.
	 */
	public function merge(
		array $exchangeCategories,
		array $manualCategories
	): array {

		/*
         * Объединяем оба массива.
         *
         * Категории из обмена идут первыми,
         * затем ручные категории.
         */
		$categories = array_merge(
			$exchangeCategories,
			$manualCategories
		);

		/*
         * Удаляем возможные дубликаты.
         */
		$categories = array_unique($categories);

		/*
         * Восстанавливаем последовательные индексы.
         */
		$categories = array_values($categories);

		/*
         * Приводим все значения к целому типу.
         *
         * Это избавляет от возможных строковых
         * значений вида "15".
         */
		return array_map(
			'intval',
			$categories
		);
	}
}
