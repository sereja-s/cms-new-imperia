<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Services;

use BytePerfect\EDI\Utils;
use Exception;
use WP_Term;

/**
 * ==========================================================
 * CategoryService
 * ==========================================================
 *
 * Сервис работы с категориями WooCommerce.
 *
 * -----------------------------------------------------------------
 * Назначение
 * -----------------------------------------------------------------
 *
 * Данный класс инкапсулирует всю работу
 * непосредственно с категориями WooCommerce.
 *
 * Он НЕ знает ничего:
 *
 * • о CommerceML;
 * • о структуре XML;
 * • о GUID;
 * • о 1С;
 * • о сопоставлении объектов.
 *
 * Благодаря этому его можно использовать
 * из любого другого модуля Imperia Core.
 *
 * -----------------------------------------------------------------
 * Почему это лучше оригинального EDI
 * -----------------------------------------------------------------
 *
 * В оригинальном CategoriesParser EDI
 * одновременно выполнялись:
 *
 * • поиск категории;
 * • создание категории;
 * • обновление категории;
 * • работа с XML;
 * • работа с GUID.
 *
 * Мы разделяем ответственность.
 *
 * Этот сервис отвечает исключительно
 * за работу с категориями WooCommerce.
 */
final class CategoryService
{
	/**
	 * ======================================================
	 * Найти категорию по ID.
	 * ======================================================
	 *
	 * Возвращает объект WP_Term
	 * либо null.
	 */
	public function findById(
		int $termId
	): ?WP_Term {

		$term = get_term_by(
			'id',
			$termId,
			'product_cat'
		);

		return $term instanceof WP_Term
			? $term
			: null;
	}

	/**
	 * ======================================================
	 * Найти категорию по названию.
	 * ======================================================
	 *
	 * Используется тогда,
	 * когда категория ещё не сопоставлена
	 * с GUID из 1С.
	 *
	 * Возвращает объект категории
	 * либо null.
	 */
	public function findByName(
		string $name
	): ?WP_Term {

		$term = get_term_by(
			'name',
			$this->sanitizeName($name),
			'product_cat'
		);

		return $term instanceof WP_Term
			? $term
			: null;
	}

	/**
	 * ======================================================
	 * Проверить существование категории.
	 * ======================================================
	 *
	 * Используется после поиска по GUID,
	 * чтобы определить,
	 * не была ли категория удалена вручную.
	 */
	public function exists(
		int $termId
	): bool {

		return $this->findById($termId) !== null;
	}

	/**
	 * ======================================================
	 * Создать категорию WooCommerce.
	 * ======================================================
	 *
	 * Использует практически тот же алгоритм,
	 * что и оригинальный EDI.
	 *
	 * Разница лишь в том,
	 * что вся логика вынесена
	 * в отдельный сервис.
	 *
	 * Возвращает ID новой категории.
	 *
	 * @throws Exception
	 */
	public function create(
		string $name,
		int $parentId = 0
	): int {

		/*
         * --------------------------------------------------
         * Проверяем существование родительской категории.
         * --------------------------------------------------
         *
         * Это полностью повторяет поведение EDI.
         */

		if (
			$parentId > 0 &&
			! $this->exists($parentId)
		) {

			$message = sprintf(
				'Parent category %d does not exist.',
				$parentId
			);

			imperia_log('ERROR: ' . $message);

			throw new Exception($message);
		}

		/*
         * --------------------------------------------------
         * Подготавливаем название.
         * --------------------------------------------------
         */

		$name = $this->sanitizeName($name);

		/*
         * --------------------------------------------------
         * Создаём категорию WooCommerce.
         * --------------------------------------------------
         */

		$result = wp_insert_term(

			$name,

			'product_cat',

			[

				'parent' => $parentId,

				'slug' => $this->makeSlug($name),

			]

		);

		/*
         * --------------------------------------------------
         * WordPress сообщил об ошибке.
         * --------------------------------------------------
         */

		if (is_wp_error($result)) {

			$message = sprintf(
				'Cannot create WooCommerce category "%s". %s',
				$name,
				$result->get_error_message()
			);

			imperia_log('ERROR: ' . $message);

			throw new Exception($message);
		}

		/*
         * Возвращаем ID новой категории.
         */

		return (int) $result['term_id'];
	}

	/**
	 * ======================================================
	 * Подготовить название категории.
	 * ======================================================
	 *
	 * Используется тот же алгоритм,
	 * что и в оригинальном EDI.
	 */
	public function sanitizeName(
		string $name
	): string {

		return wc_clean(
			wp_unslash($name)
		);
	}

	/**
	 * ======================================================
	 * Сформировать slug категории.
	 * ======================================================
	 *
	 * Здесь мы специально используем
	 * Utils::transliterate()
	 * из оригинального EDI.
	 *
	 * Это позволяет полностью сохранить
	 * совместимость с существующим поведением.
	 */
	public function makeSlug(
		string $name
	): string {

		/*
         * Подготавливаем строку.
         */

		$slug = wc_sanitize_taxonomy_name(
			$this->sanitizeName($name)
		);

		/*
         * Используем алгоритм EDI.
         */

		$slug = Utils::transliterate(
			$slug
		);

		/*
         * EDI ограничивает длину slug.
         */

		return substr(
			$slug,
			0,
			200
		);
	}
}
