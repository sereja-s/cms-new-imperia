<?php

declare(strict_types=1);

namespace Imperia\Modules\EDI\Services;

use Imperia\Modules\EDI\Infrastructure\MappingKeys;
use WC_Product;

/**
 * ==========================================================
 * ManagedCategoryService
 * ==========================================================
 *
 * Определяет,
 * какие категории товара
 * находятся под управлением обмена с 1С.
 *
 * ----------------------------------------------------------
 * Зачем нужен этот сервис
 * ----------------------------------------------------------
 *
 * После первого обмена товар может иметь категории:
 *
 *      Ламинат
 *      Quick Step
 *
 * Позже администратор сайта может вручную добавить:
 *
 *      Акция
 *      Хиты продаж
 *      Новинки
 *
 * Во время следующего обмена 1С
 * не должна удалить эти категории.
 *
 * Для этого необходимо понимать,
 * какие категории принадлежат обмену,
 * а какие были добавлены вручную.
 *
 * ----------------------------------------------------------
 * Где хранится информация
 * ----------------------------------------------------------
 *
 * Нигде.
 *
 * Мы используем существующий mapping EDI.
 *
 * Если категория присутствует
 * в _edi_1c_category_map,
 * значит именно она была создана
 * либо сопоставлена во время обмена.
 *
 * Следовательно,
 * такая категория считается
 * управляемой обменом.
 *
 * ----------------------------------------------------------
 * Преимущества
 * ----------------------------------------------------------
 *
 * ✔ нет собственного хранилища;
 *
 * ✔ нет дублирования данных;
 *
 * ✔ используется штатный механизм EDI;
 *
 * ✔ удаление mapping автоматически
 * исключает категорию
 * из управляемых.
 */
final class ManagedCategoryService
{
	/**
	 * Все GUID → ID категорий,
	 * зарегистрированные EDI.
	 *
	 * Формат:
	 *
	 * [
	 *      GUID => term_id
	 * ]
	 */
	private array $mapping;

	/**
	 * Загружаем mapping EDI.
	 *
	 * Он хранится в options WordPress.
	 */
	public function __construct()
	{
		$mapping = get_option(
			MappingKeys::CATEGORY,
			[]
		);

		$this->mapping = is_array($mapping)
			? $mapping
			: [];
	}

	/**
	 * ======================================================
	 * Получить категории товара,
	 * принадлежащие обмену.
	 * ======================================================
	 *
	 * Возвращает только те категории,
	 * которые имеются в mapping EDI.
	 *
	 * Именно ими имеет право
	 * управлять обмен.
	 *
	 * Остальные категории
	 * считаются добавленными вручную.
	 *
	 * @return int[]
	 */
	public function getManagedCategories(
		WC_Product $product
	): array {

		$managed = [];

		/*
         * Получаем все категории товара.
         */
		foreach ($product->get_category_ids() as $categoryId) {

			/*
             * Проверяем,
             * существует ли данный term_id
             * среди значений mapping EDI.
             *
             * Если существует —
             * категория управляется обменом.
             */
			if (in_array(
				$categoryId,
				$this->mapping,
				true
			)) {
				$managed[] = (int) $categoryId;
			}
		}

		return $managed;
	}

	/**
	 * ======================================================
	 * Проверить,
	 * управляется ли категория обменом.
	 * ======================================================
	 *
	 * Может пригодиться
	 * в других сервисах.
	 */
	public function isManaged(
		int $categoryId
	): bool {

		return in_array(
			$categoryId,
			$this->mapping,
			true
		);
	}
}
