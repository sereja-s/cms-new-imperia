<?php

namespace Imperia\Modules\Catalog\Services;

/**
 * ==========================================================
 * CATEGORY TREE SERVICE
 * ==========================================================
 *
 * Сервис построения дерева категорий WooCommerce.
 *
 * Ответственность:
 *
 * - получить категории product_cat;
 * - построить дерево в памяти PHP;
 * - подготовить данные для меню.
 *
 * НЕ отвечает за:
 *
 * - кэширование;
 * - HTML;
 * - CSS;
 * - JavaScript;
 * - AJAX.
 *
 * Архитектура:
 *
 * CategoryCache
 *        |
 *        ↓
 * CategoryTree
 *        |
 *        ↓
 * get_terms()
 *
 * ==========================================================
 *
 * Возвращаемая структура:
 *
 * [
 *     [
 *         'id'       => 15,
 *         'name'     => 'Ламинат',
 *         'slug'     => 'laminat',
 *         'url'      => '/product-category/laminat/',
 *         'children' => [
 *
 *             [
 *                 'id'   => 20,
 *                 'name' => 'Дуб',
 *                 'url'  => '/product-category/laminat/dub/',
 *             ]
 *
 *         ]
 *     ]
 * ]
 *
 * Эта структура подходит для:
 *
 * - desktop mega menu;
 * - мобильного меню;
 * - JS переключения категорий;
 * - будущего AJAX.
 *
 * ==========================================================
 */
final class CategoryTree
{

	/**
	 * ======================================================
	 * TERMS MAP
	 * ======================================================
	 *
	 * Карта категорий по ID.
	 *
	 * Пример:
	 *
	 * [
	 *     15 => WP_Term,
	 *     20 => WP_Term,
	 * ]
	 *
	 * Используется чтобы не искать
	 * категории повторно.
	 *
	 * Вместо:
	 *
	 * foreach
	 *     get_term()
	 *
	 * получаем:
	 *
	 * один запрос + работа с массивами.
	 *
	 * @var array<int,\WP_Term>
	 */
	private array $termsMap = [];


	/**
	 * ======================================================
	 * CHILDREN INDEX
	 * ======================================================
	 *
	 * Индекс дочерних категорий.
	 *
	 * Формат:
	 *
	 * [
	 *     0  => [15,18],
	 *     15 => [20,21],
	 * ]
	 *
	 * Где:
	 *
	 * ключ:
	 *     ID родителя
	 *
	 * значение:
	 *     массив ID детей
	 *
	 * ======================================================
	 *
	 * @var array<int,array<int>>
	 */
	private array $childrenIndex = [];


	/**
	 * ======================================================
	 * GET TREE
	 * ======================================================
	 *
	 * Главный публичный метод.
	 *
	 * Выполняет:
	 *
	 * 1. Получает категории WooCommerce.
	 * 2. Создаёт индексы.
	 * 3. Строит дерево.
	 *
	 * ======================================================
	 */
	public function getTree(): array
	{

		/**
		 * Получаем все категории товаров.
		 *
		 * Важно:
		 *
		 * hide_empty = false
		 *
		 * Показываем категории даже без товаров.
		 *
		 * Исключение:
		 * категория WooCommerce по умолчанию
		 * дополнительно фильтруется ниже.
		 *
		 * Например:
		 *
		 * "Новая коллекция"
		 *
		 * ещё без товаров,
		 * но уже создана в каталоге.
		 */
		$terms = get_terms(
			[
				'taxonomy'   => 'product_cat',

				'hide_empty' => false,

				'number'     => 0,

				'orderby'    => 'name',

				'order'      => 'ASC',
			]
		);


		/**
		 * Не удалось получить категории
		 * либо список категорий пуст.
		 */
		if (
			is_wp_error($terms)
			|| empty($terms)
		) {
			return [];
		}

		/**
		 * ======================================================
		 * DEFAULT WOOCOMMERCE CATEGORY
		 * ======================================================
		 *
		 * WooCommerce всегда имеет одну категорию
		 * по умолчанию (Default Product Category).
		 *
		 * Обычно это:
		 *
		 * Uncategorized
		 *
		 * но владелец магазина может:
		 *
		 * - переименовать её;
		 * - изменить slug;
		 * - назначить другую категорию
		 *   категорией по умолчанию.
		 *
		 * Поэтому нельзя ориентироваться
		 * на название или slug.
		 *
		 * Получаем ID дефолтной категории
		 * из настроек WooCommerce.
		 */
		$defaultCategoryId =
			(int) get_option(
				'default_product_cat'
			);

		/**
		 * ======================================================
		 * CATEGORY FILTER
		 * ======================================================
		 *
		 * Правила отображения:
		 *
		 * 1. Все обычные категории
		 *    показываем всегда,
		 *    даже если товаров нет.
		 *
		 * 2. Дефолтную категорию WooCommerce
		 *    показываем только тогда,
		 *    когда в ней есть товары.
		 *
		 * Это позволяет:
		 *
		 * - не засорять каталог пустой
		 *   служебной категорией;
		 *
		 * - сохранить доступ к товарам,
		 *   если они действительно находятся
		 *   в категории по умолчанию.
		 */
		$terms = array_filter(
			$terms,
			static function ($term) use (
				$defaultCategoryId
			) {

				/**
				 * Обычная категория.
				 */
				if (
					(int) $term->term_id !==
					$defaultCategoryId
				) {
					return true;
				}

				/**
				 * Категория по умолчанию.
				 *
				 * Показываем только если
				 * содержит товары.
				 */
				return $term->count > 0;
			}
		);

		if (empty($terms)) {
			return [];
		}

		/**
		 * Подготавливаем индексы.
		 */
		$this->buildIndexes(
			$terms
		);


		/**
		 * Начинаем построение
		 * с корневых категорий.
		 *
		 * В WordPress:
		 *
		 * parent = 0
		 *
		 * означает:
		 *
		 * категория верхнего уровня.
		 */
		return $this->buildBranch(0);
	}


	/**
	 * ======================================================
	 * BUILD INDEXES
	 * ======================================================
	 *
	 * Создаёт быстрые структуры:
	 *
	 * 1. ID -> категория
	 *
	 * 2. parent -> children
	 *
	 * После выполнения:
	 *
	 * запросы к БД больше не нужны.
	 *
	 * ======================================================
	 */
	private function buildIndexes(
		array $terms
	): void {

		$this->termsMap = [];

		$this->childrenIndex = [];


		foreach ($terms as $term) {


			/**
			 * Сохраняем категорию
			 * по ID.
			 */
			$this->termsMap[$term->term_id] = $term;



			/**
			 * Если родитель ещё
			 * не зарегистрирован,
			 * создаём массив детей.
			 */
			if (
				!isset(
					$this->childrenIndex[$term->parent]
				)
			) {

				$this->childrenIndex[$term->parent] = [];
			}


			/**
			 * Добавляем ребёнка.
			 */
			$this->childrenIndex[$term->parent][] = $term->term_id;
		}
	}


	/**
	 * ======================================================
	 * BUILD BRANCH
	 * ======================================================
	 *
	 * Рекурсивно строит дерево.
	 *
	 * Важно:
	 *
	 * Здесь уже нет запросов БД.
	 *
	 * Только массивы PHP.
	 *
	 * ======================================================
	 */
	private function buildBranch(
		int $parentId
	): array {


		$branch = [];


		/**
		 * У родителя нет детей.
		 */
		if (
			!isset(
				$this->childrenIndex[$parentId]
			)
		) {

			return [];
		}


		foreach (
			$this->childrenIndex[$parentId]
			as $childId
		) {


			$term =
				$this->termsMap[$childId];



			/**
			 * Получаем ссылку категории.
			 *
			 * get_term_link()
			 * может вернуть WP_Error,
			 * поэтому делаем проверку.
			 */
			$url =
				get_term_link(
					$term
				);


			if (
				is_wp_error($url)
			) {

				$url = '#';
			}



			$branch[] = [

				/**
				 * ID категории.
				 *
				 * Нужен JS для переключения.
				 */
				'id' =>
				$term->term_id,


				/**
				 * Название.
				 */
				'name' =>
				$term->name,


				/**
				 * Slug.
				 */
				'slug' =>
				$term->slug,


				/**
				 * URL категории.
				 *
				 * Теперь меню сможет
				 * использовать ссылки.
				 */
				'url' =>
				$url,


				/**
				 * Дети.
				 *
				 * Рекурсия.
				 */
				'children' =>
				$this->buildBranch(
					$term->term_id
				),

			];
		}


		return $branch;
	}
}
