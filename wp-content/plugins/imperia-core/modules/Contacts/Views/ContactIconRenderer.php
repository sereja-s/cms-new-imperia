final class ContactIconRenderer
{
	/**
	 * Получить SVG иконку.
	 *
	 * @param string $type
	 *
	 * @return string
	 */
	public function render(
		string $type
	): string {

		switch ($type) {

			case 'phone':
				return $this->phone();

			case 'telegram':
				return $this->telegram();

			case 'max':
				return $this->max();

			case 'contact':
				return $this->contact();

			case 'arrow':
				return $this->arrow();
		}

		return '';
	}

