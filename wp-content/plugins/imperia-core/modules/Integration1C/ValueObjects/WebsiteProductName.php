<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\ValueObjects;

use Imperia\Modules\Integration1C\Contracts\ValueObjectInterface;

/**
 * ==========================================================================
 * WEBSITE PRODUCT NAME
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет дополнительное название товара,
 * предназначенное для публикации на сайте.
 *
 * Данное поле является необязательным.
 *
 * Если значение отсутствует,
 * при публикации товара используется ProductName.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 * - хранение названия товара для сайта;
 * - нормализация значения при создании;
 * - безопасное сравнение с другим объектом
 *   WebsiteProductName;
 * - предоставление значения в неизменном виде.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 * - выбор отображаемого названия;
 * - SEO;
 * - генерацию URL;
 * - сохранение данных;
 * - обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 * - пробелы в начале и конце автоматически удаляются;
 * - пустая строка является допустимым значением;
 * - после создания значение не изменяется;
 * - объект является неизменяемым (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 * Создаётся при чтении данных обмена из 1С
 * и сопровождает карточку товара
 * на протяжении всего процесса синхронизации.
 */
final class WebsiteProductName implements ValueObjectInterface
{
	/**
	 * Название товара для сайта.
	 */
	private string $websiteProductName;

	/**
	 * Создаёт объект названия товара для сайта.
	 *
	 * @param string $websiteProductName Название товара для сайта.
	 */
	public function __construct(string $websiteProductName)
	{
		$this->websiteProductName = trim($websiteProductName);
	}

	/**
	 * Возвращает название товара для сайта.
	 */
	public function value(): string
	{
		return $this->websiteProductName;
	}

	/**
	 * Проверяет,
	 * заполнено ли название для сайта.
	 */
	public function hasValue(): bool
	{
		return $this->websiteProductName !== '';
	}

	/**
	 * Сравнивает два названия товара для сайта.
	 */
	public function equals(WebsiteProductName $other): bool
	{
		return $this->websiteProductName === $other->value();
	}

	/**
	 * Возвращает название товара для сайта
	 * в виде строки.
	 */
	public function __toString(): string
	{
		return $this->websiteProductName;
	}
}
