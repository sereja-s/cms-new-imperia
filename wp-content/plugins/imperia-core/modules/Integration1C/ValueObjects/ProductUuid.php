<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\ValueObjects;

use Imperia\Modules\Integration1C\Contracts\ValueObjectInterface;
use InvalidArgumentException;

/**
 * ==========================================================================
 * PRODUCT UUID
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет уникальный идентификатор товара,
 * полученный из информационной системы 1С.
 *
 * UUID является главным идентификатором интеграции
 * и используется для поиска соответствующего товара
 * в каталоге WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 * - хранение уникального идентификатора товара;
 * - проверка корректности значения при создании;
 * - безопасное сравнение двух идентификаторов;
 * - предоставление значения в неизменном виде.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 * - генерацию UUID;
 * - проверку существования товара;
 * - поиск товара;
 * - сохранение в базе данных;
 * - обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 * - UUID не может быть пустым;
 * - после создания значение не изменяется;
 * - объект является неизменяемым (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 * Создаётся при чтении данных обмена из 1С
 * и сопровождает карточку товара
 * на протяжении всего процесса синхронизации.
 */
final class ProductUuid implements ValueObjectInterface
{
	/**
	 * Уникальный идентификатор товара.
	 */
	private string $productUuid;

	/**
	 * Создаёт объект уникального идентификатора товара.
	 *
	 * @param string $productUuid UUID, полученный из 1С.
	 *
	 * @throws InvalidArgumentException
	 * Если идентификатор пустой.
	 */
	public function __construct(string $productUuid)
	{
		$productUuid = trim($productUuid);

		if ($productUuid === '') {
			throw new InvalidArgumentException(
				'Уникальный идентификатор товара не может быть пустым.'
			);
		}

		$this->productUuid = $productUuid;
	}

	/**
	 * Возвращает UUID товара.
	 */
	public function value(): string
	{
		return $this->productUuid;
	}

	/**
	 * Сравнивает UUID двух товаров.
	 */
	public function equals(ProductUuid $other): bool
	{
		return $this->productUuid === $other->value();
	}

	/**
	 * Возвращает UUID в виде строки.
	 */
	public function __toString(): string
	{
		return $this->productUuid;
	}
}
