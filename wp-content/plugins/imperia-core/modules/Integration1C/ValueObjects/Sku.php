<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\ValueObjects;

use Imperia\Modules\Integration1C\Contracts\ValueObjectInterface;
use InvalidArgumentException;

/**
 * ==========================================================================
 * SKU
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет артикул товара в доменной модели Integration1C.
 *
 * Объект гарантирует корректность артикула после создания
 * и исключает работу с "сырыми" строками в предметной области.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 * - хранение артикула товара;
 * - проверка корректности при создании;
 * - безопасное сравнение с другим объектом Sku;
 * - предоставление значения в неизменном виде.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 * - поиск товара;
 * - генерацию артикула;
 * - проверку уникальности;
 * - сохранение в базе данных;
 * - обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 * - артикул не может быть пустым;
 * - артикул хранится без изменений после создания;
 * - объект является неизменяемым (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 * Создаётся при построении ProductCard
 * и используется всеми сервисами, которым требуется
 * безопасная работа с артикулом товара.
 */
final class Sku implements ValueObjectInterface
{
	/**
	 * Артикул товара.
	 */
	private string $sku;

	/**
	 * Создаёт объект артикула.
	 *
	 * @param string $sku Артикул, полученный из 1С.
	 *
	 * @throws InvalidArgumentException Если артикул пустой.
	 */
	public function __construct(string $sku)
	{
		$sku = trim($sku);

		if ($sku === '') {
			throw new InvalidArgumentException(
				'Артикул товара не может быть пустым.'
			);
		}

		$this->sku = $sku;
	}

	/**
	 * Возвращает артикул товара.
	 */
	public function value(): string
	{
		return $this->sku;
	}

	/**
	 * Сравнивает артикулы двух товаров.
	 */
	public function equals(Sku $other): bool
	{
		return $this->sku === $other->value();
	}

	/**
	 * Возвращает артикул в виде строки.
	 */
	public function __toString(): string
	{
		return $this->sku;
	}
}
