<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\ValueObjects;

use Imperia\Modules\Integration1C\Contracts\ValueObjectInterface;
use InvalidArgumentException;

/**
 * ==========================================================================
 * PRICE
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет цену товара в доменной модели Integration1C.
 *
 * Объект гарантирует корректность значения после создания
 * и исключает использование "сырых" строк в предметной области.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 * - хранение цены товара;
 * - проверка корректности при создании;
 * - безопасное сравнение с другим объектом Price;
 * - предоставление значения в неизменном виде.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 * - расчёт скидок;
 * - вычисление налогов;
 * - форматирование цены;
 * - конвертацию валют;
 * - сохранение в базе данных;
 * - обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 * - цена не может быть пустой;
 * - цена должна быть числом;
 * - цена не может быть отрицательной;
 * - объект является неизменяемым (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 * Создаётся при построении ProductCard
 * и используется всеми сервисами,
 * которым требуется безопасная работа с ценой товара.
 */
final class Price implements ValueObjectInterface
{
	/**
	 * Цена товара.
	 *
	 * Хранится в строковом виде для сохранения точности значения
	 * и совместимости с форматом обмена.
	 */
	private string $price;

	/**
	 * Создаёт объект цены.
	 *
	 * @param string $price Цена товара, полученная из 1С.
	 *
	 * @throws InvalidArgumentException
	 * Если цена имеет некорректное значение.
	 */
	public function __construct(string $price)
	{
		$price = trim($price);

		if ($price === '') {
			throw new InvalidArgumentException(
				'Цена товара не может быть пустой.'
			);
		}

		if (!is_numeric($price)) {
			throw new InvalidArgumentException(
				'Цена товара должна быть числом.'
			);
		}

		if ((float) $price < 0) {
			throw new InvalidArgumentException(
				'Цена товара не может быть отрицательной.'
			);
		}

		$this->price = $price;
	}

	/**
	 * Возвращает цену товара.
	 */
	public function value(): string
	{
		return $this->price;
	}

	/**
	 * Сравнивает цены двух товаров.
	 */
	public function equals(Price $other): bool
	{
		return $this->price === $other->value();
	}

	/**
	 * Возвращает цену в виде строки.
	 */
	public function __toString(): string
	{
		return $this->price;
	}
}
