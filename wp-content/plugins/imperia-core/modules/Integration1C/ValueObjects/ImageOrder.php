<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\ValueObjects;

use Imperia\Modules\Integration1C\Contracts\ValueObjectInterface;
use InvalidArgumentException;

/**
 * ==========================================================================
 * IMAGE ORDER
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет порядковый номер изображения товара,
 * полученного из информационной системы 1С.
 *
 * Порядок изображения определяет последовательность
 * отображения изображений товара.
 *
 * Изображение с порядковым номером "1"
 * считается главным изображением товара.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 * - хранение порядкового номера изображения;
 * - проверка корректности значения при создании;
 * - определение главного изображения;
 * - безопасное сравнение с другим объектом ImageOrder;
 * - предоставление значения в неизменном виде.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 * - сортировку изображений;
 * - загрузку изображений;
 * - назначение изображения товару;
 * - сохранение в базе данных;
 * - обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 * - порядковый номер должен быть больше нуля;
 * - после создания значение не изменяется;
 * - объект является неизменяемым (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 * Создаётся при построении ProductImage
 * и сопровождает изображение
 * на протяжении всего процесса обмена.
 */
final class ImageOrder implements ValueObjectInterface
{
	/**
	 * Порядковый номер изображения.
	 */
	private int $imageOrder;

	/**
	 * Создаёт объект порядкового номера изображения.
	 *
	 * @param int $imageOrder Порядковый номер изображения.
	 *
	 * @throws InvalidArgumentException
	 * Если номер меньше единицы.
	 */
	public function __construct(int $imageOrder)
	{
		if ($imageOrder < 1) {
			throw new InvalidArgumentException(
				'Порядковый номер изображения должен быть больше нуля.'
			);
		}

		$this->imageOrder = $imageOrder;
	}

	/**
	 * Возвращает порядковый номер изображения.
	 */
	public function value(): int
	{
		return $this->imageOrder;
	}

	/**
	 * Проверяет,
	 * является ли изображение главным.
	 */
	public function isPrimary(): bool
	{
		return $this->imageOrder === 1;
	}

	/**
	 * Сравнивает порядковые номера изображений.
	 */
	public function equals(ImageOrder $other): bool
	{
		return $this->imageOrder === $other->value();
	}

	/**
	 * Возвращает порядковый номер изображения в виде строки.
	 */
	public function __toString(): string
	{
		return (string) $this->imageOrder;
	}
}
