<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\ValueObjects;

use Imperia\Modules\Integration1C\Contracts\ValueObjectInterface;
use InvalidArgumentException;

/**
 * ==========================================================================
 * PRODUCT NAME
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет основное наименование товара,
 * полученное из информационной системы 1С.
 *
 * Данное название является официальным названием товара
 * в системе учёта и используется как основной источник
 * данных при синхронизации.
 *
 * Если дополнительное поле "Название для сайта"
 * отсутствует или не заполнено,
 * именно ProductName используется
 * для публикации товара на сайте.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 * - хранение наименования товара;
 * - проверка корректности значения при создании;
 * - безопасное сравнение с другим объектом ProductName;
 * - предоставление значения в неизменном виде.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 * - выбор отображаемого названия на сайте;
 * - SEO;
 * - генерацию URL;
 * - сохранение данных;
 * - обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 * - наименование товара не может быть пустым;
 * - пробелы в начале и конце автоматически удаляются;
 * - после создания значение не изменяется;
 * - объект является неизменяемым (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 * Создаётся при чтении данных обмена из 1С
 * и сопровождает карточку товара
 * на протяжении всего процесса синхронизации.
 */
final class ProductName implements ValueObjectInterface
{
	/**
	 * Наименование товара.
	 */
	private string $productName;

	/**
	 * Создаёт объект наименования товара.
	 *
	 * @param string $productName Наименование товара.
	 *
	 * @throws InvalidArgumentException
	 * Если наименование пустое.
	 */
	public function __construct(string $productName)
	{
		$productName = trim($productName);

		if ($productName === '') {
			throw new InvalidArgumentException(
				'Наименование товара не может быть пустым.'
			);
		}

		$this->productName = $productName;
	}

	/**
	 * Возвращает наименование товара.
	 */
	public function value(): string
	{
		return $this->productName;
	}

	/**
	 * Сравнивает два наименования товара.
	 */
	public function equals(ProductName $other): bool
	{
		return $this->productName === $other->value();
	}

	/**
	 * Возвращает наименование товара в виде строки.
	 */
	public function __toString(): string
	{
		return $this->productName;
	}
}
