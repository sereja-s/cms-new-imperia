<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\ValueObjects;

use Imperia\Modules\Integration1C\Contracts\ValueObjectInterface;
use InvalidArgumentException;

/**
 * ==========================================================================
 * GROUP UUID
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет уникальный идентификатор группы товаров,
 * полученный из информационной системы 1С.
 *
 * UUID является техническим идентификатором группы
 * и используется для надёжного сопоставления группы 1С
 * с категорией WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 * - хранение уникального идентификатора группы;
 * - проверка корректности значения при создании;
 * - безопасное сравнение двух идентификаторов;
 * - предоставление значения в неизменном виде.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 * - генерацию UUID;
 * - проверку существования группы;
 * - поиск категории WooCommerce;
 * - сохранение в базе данных;
 * - обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 * - UUID не может быть пустым;
 * - после создания значение не изменяется;
 * - объект является неизменяемым (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 * Создаётся при чтении данных обмена из 1С
 * и сопровождает группу товаров
 * на протяжении всего процесса синхронизации.
 */
final class GroupUuid implements ValueObjectInterface
{
	/**
	 * Уникальный идентификатор группы.
	 */
	private string $groupUuid;

	/**
	 * Создаёт объект уникального идентификатора группы.
	 *
	 * @param string $groupUuid UUID, полученный из 1С.
	 *
	 * @throws InvalidArgumentException
	 * Если идентификатор пустой.
	 */
	public function __construct(string $groupUuid)
	{
		$groupUuid = trim($groupUuid);

		if ($groupUuid === '') {
			throw new InvalidArgumentException(
				'Уникальный идентификатор группы не может быть пустым.'
			);
		}

		$this->groupUuid = $groupUuid;
	}

	/**
	 * Возвращает UUID группы.
	 */
	public function value(): string
	{
		return $this->groupUuid;
	}

	/**
	 * Сравнивает UUID двух групп.
	 */
	public function equals(GroupUuid $other): bool
	{
		return $this->groupUuid === $other->value();
	}

	/**
	 * Возвращает UUID группы в виде строки.
	 */
	public function __toString(): string
	{
		return $this->groupUuid;
	}
}
