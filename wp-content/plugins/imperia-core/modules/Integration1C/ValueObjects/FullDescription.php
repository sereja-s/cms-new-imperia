<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\ValueObjects;

use Imperia\Modules\Integration1C\Contracts\ValueObjectInterface;

/**
 * ==========================================================================
 * FULL DESCRIPTION
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет полное описание товара,
 * полученное из информационной системы 1С.
 *
 * Полное описание является необязательной частью
 * карточки товара.
 *
 * Если описание отсутствует,
 * товар может быть опубликован
 * только с кратким описанием.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 * - хранение полного описания товара;
 * - нормализация значения при создании;
 * - безопасное сравнение с другим объектом
 *   FullDescription;
 * - предоставление значения в неизменном виде.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 * - SEO-оптимизацию текста;
 * - форматирование HTML;
 * - обработку изображений;
 * - сохранение данных;
 * - обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 * - пробелы в начале и конце автоматически удаляются;
 * - пустая строка является допустимым значением;
 * - после создания значение не изменяется;
 * - объект является неизменяемым (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 * Создаётся при чтении данных обмена из 1С
 * и сопровождает карточку товара
 * на протяжении всего процесса синхронизации.
 */
final class FullDescription implements ValueObjectInterface
{
	/**
	 * Полное описание товара.
	 */
	private string $fullDescription;

	/**
	 * Создаёт объект полного описания товара.
	 *
	 * @param string $fullDescription Полное описание товара.
	 */
	public function __construct(string $fullDescription)
	{
		$this->fullDescription = trim($fullDescription);
	}

	/**
	 * Возвращает полное описание товара.
	 */
	public function value(): string
	{
		return $this->fullDescription;
	}

	/**
	 * Проверяет,
	 * заполнено ли полное описание товара.
	 */
	public function hasValue(): bool
	{
		return $this->fullDescription !== '';
	}

	/**
	 * Сравнивает два полных описания товара.
	 */
	public function equals(FullDescription $other): bool
	{
		return $this->fullDescription === $other->value();
	}

	/**
	 * Возвращает полное описание товара
	 * в виде строки.
	 */
	public function __toString(): string
	{
		return $this->fullDescription;
	}
}
