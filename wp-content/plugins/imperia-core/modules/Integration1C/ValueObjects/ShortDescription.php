<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\ValueObjects;

use Imperia\Modules\Integration1C\Contracts\ValueObjectInterface;
use InvalidArgumentException;

/**
 * ==========================================================================
 * SHORT DESCRIPTION
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет краткое описание товара,
 * полученное из информационной системы 1С.
 *
 * Краткое описание является обязательной частью
 * карточки товара и используется при публикации
 * товара на сайте.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 * - хранение краткого описания;
 * - проверка корректности значения при создании;
 * - безопасное сравнение с другим объектом
 *   ShortDescription;
 * - предоставление значения в неизменном виде.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 * - SEO-оптимизацию текста;
 * - форматирование HTML;
 * - обработку изображений;
 * - сохранение данных;
 * - обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 * - краткое описание не может быть пустым;
 * - пробелы в начале и конце автоматически удаляются;
 * - после создания значение не изменяется;
 * - объект является неизменяемым (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 * Создаётся при чтении данных обмена из 1С
 * и сопровождает карточку товара
 * на протяжении всего процесса синхронизации.
 */
final class ShortDescription implements ValueObjectInterface
{
	/**
	 * Краткое описание товара.
	 */
	private string $shortDescription;

	/**
	 * Создаёт объект краткого описания товара.
	 *
	 * @param string $shortDescription Краткое описание товара.
	 *
	 * @throws InvalidArgumentException
	 * Если описание пустое.
	 */
	public function __construct(string $shortDescription)
	{
		$shortDescription = trim($shortDescription);

		if ($shortDescription === '') {
			throw new InvalidArgumentException(
				'Краткое описание товара не может быть пустым.'
			);
		}

		$this->shortDescription = $shortDescription;
	}

	/**
	 * Возвращает краткое описание товара.
	 */
	public function value(): string
	{
		return $this->shortDescription;
	}

	/**
	 * Сравнивает два кратких описания товара.
	 */
	public function equals(ShortDescription $other): bool
	{
		return $this->shortDescription === $other->value();
	}

	/**
	 * Возвращает краткое описание товара
	 * в виде строки.
	 */
	public function __toString(): string
	{
		return $this->shortDescription;
	}
}
