<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Contracts;

/**
 * ==========================================================================
 * COLLECTION INTERFACE
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Маркерный интерфейс всех коллекций предметной области
 * модуля Integration1C.
 *
 * --------------------------------------------------------------------------
 * Что считается коллекцией
 * --------------------------------------------------------------------------
 * Коллекция представляет объект предметной области,
 * предназначенный для хранения нескольких объектов
 * одного типа.
 *
 * В отличие от обычного массива,
 * коллекция гарантирует соблюдение правил
 * предметной области и предоставляет
 * единый интерфейс работы с элементами.
 *
 * Примеры коллекций:
 *
 * - ImageCollection
 * - GroupCollection
 * - ProductCollection
 * - ExchangePackageCollection
 *
 * --------------------------------------------------------------------------
 * Ответственность интерфейса
 * --------------------------------------------------------------------------
 * Интерфейс не определяет обязательных методов.
 *
 * Его задача — обозначить принадлежность класса
 * к слою Collections архитектуры Integration1C.
 *
 * --------------------------------------------------------------------------
 * Почему интерфейс пустой
 * --------------------------------------------------------------------------
 * Различные коллекции могут предоставлять
 * различное поведение.
 *
 * Например:
 *
 * - поиск главного изображения;
 * - поиск товара по UUID;
 * - поиск группы по идентификатору;
 * - получение статистики.
 *
 * Введение обязательных методов привело бы
 * к искусственным ограничениям архитектуры
 * и нарушению принципа единственной ответственности.
 *
 * Поэтому данный интерфейс используется
 * исключительно как маркер.
 */
interface CollectionInterface {}
