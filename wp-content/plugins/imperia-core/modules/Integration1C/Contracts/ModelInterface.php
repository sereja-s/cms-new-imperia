<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Contracts;

/**
 * ==========================================================================
 * MODEL INTERFACE
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Маркерный интерфейс всех моделей предметной области
 * модуля Integration1C.
 *
 * --------------------------------------------------------------------------
 * Что считается моделью
 * --------------------------------------------------------------------------
 * Модель представляет объект предметной области,
 * который участвует в процессе обмена между
 * информационной системой 1С и интернет-магазином.
 *
 * Примеры моделей:
 *
 * - ProductImage
 * - GroupReference
 * - ProductCard
 * - ExchangePackage
 * - ExchangePlan
 * - ExchangeSession
 * - ExchangeStatistics
 * - ExchangeReport
 *
 * --------------------------------------------------------------------------
 * Ответственность интерфейса
 * --------------------------------------------------------------------------
 * Интерфейс не определяет обязательных методов.
 *
 * Его задача — обозначить принадлежность класса
 * к слою Models архитектуры Integration1C.
 *
 * --------------------------------------------------------------------------
 * Почему интерфейс пустой
 * --------------------------------------------------------------------------
 * Не все модели имеют одинаковое поведение.
 *
 * Введение обязательных методов привело бы
 * к искусственным ограничениям архитектуры
 * и нарушению принципа единственной ответственности.
 *
 * Поэтому данный интерфейс используется
 * исключительно как маркер.
 */
interface ModelInterface {}
