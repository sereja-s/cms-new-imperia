<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Enums;

/**
 * ==========================================================================
 * VALIDATION MESSAGE CODE
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Определяет допустимые коды сообщений проверки,
 * используемые модулем Integration1C.
 *
 * Код сообщения является машинным идентификатором,
 * позволяющим однозначно определить
 * тип результата проверки.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 *
 * • определяет допустимые коды сообщений;
 * • обеспечивает типобезопасность;
 * • исключает использование строковых литералов.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 *
 * • выполнение проверки;
 * • отображение сообщений;
 * • локализацию текста;
 * • бизнес-логику обмена.
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 *
 * Используется фабрикой ValidationMessageFactory
 * и всеми сервисами проверки данных.
 */
enum ValidationMessageCode: string
{
	/**
	 * Проверка успешно завершена.
	 */
	case VALIDATION_COMPLETED = 'VALIDATION_COMPLETED';

	/**
	 * Не найден UUID товара.
	 */
	case PRODUCT_UUID_MISSING = 'PRODUCT_UUID_MISSING';

	/**
	 * Не указан артикул товара.
	 */
	case SKU_MISSING = 'SKU_MISSING';

	/**
	 * Не указано название товара.
	 */
	case PRODUCT_NAME_MISSING = 'PRODUCT_NAME_MISSING';

	/**
	 * Не указано краткое описание.
	 */
	case SHORT_DESCRIPTION_MISSING = 'SHORT_DESCRIPTION_MISSING';

	/**
	 * Не указана цена товара.
	 */
	case PRICE_MISSING = 'PRICE_MISSING';

	/**
	 * Цена товара имеет неверный формат.
	 */
	case PRICE_INVALID = 'PRICE_INVALID';

	/**
	 * Не найдена группа товара.
	 */
	case GROUP_NOT_FOUND = 'GROUP_NOT_FOUND';

	/**
	 * Не найдены изображения товара.
	 */
	case IMAGES_MISSING = 'IMAGES_MISSING';
}
