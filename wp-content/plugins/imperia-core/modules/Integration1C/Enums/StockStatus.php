<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Enums;

/**
 * ==========================================================================
 * STOCK STATUS
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Определяет состояние наличия товара в доменной модели Integration1C.
 *
 * Перечисление используется внутри системы и не зависит
 * от форматов хранения данных WooCommerce, WordPress или 1С.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 *
 * - описывает допустимые состояния наличия товара;
 * - предоставляет доменные методы работы с состоянием;
 * - обеспечивает типобезопасность вместо строковых литералов.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 *
 * - хранение товара;
 * - преобразование в значения WooCommerce;
 * - чтение данных из 1С;
 * - запись данных в WordPress.
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 *
 * Используется всеми объектами предметной области,
 * которым требуется определить состояние наличия товара.
 */
enum StockStatus: string
{
	/**
	 * Товар доступен для покупки.
	 */
	case IN_STOCK = 'in_stock';

	/**
	 * Товар отсутствует.
	 */
	case OUT_OF_STOCK = 'out_of_stock';
}
