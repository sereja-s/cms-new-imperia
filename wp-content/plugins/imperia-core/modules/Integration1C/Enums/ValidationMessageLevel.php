<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Enums;

/**
 * ==========================================================================
 * VALIDATION MESSAGE LEVEL
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Определяет уровень сообщения проверки,
 * сформированного во время обработки данных обмена.
 *
 * Уровень сообщения используется
 * для классификации результатов проверки.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 *
 * • определяет допустимые уровни сообщений;
 * • обеспечивает типобезопасность;
 * • исключает использование строковых литералов.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 *
 * • выполнение проверки;
 * • отображение сообщений;
 * • обработку ошибок;
 * • бизнес-логику обмена.
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 *
 * Используется объектами ValidationMessage
 * и ValidationMessageFactory
 * при формировании результатов проверки.
 */
enum ValidationMessageLevel: string
{
	/**
	 * Ошибка.
	 */
	case ERROR = 'error';

	/**
	 * Предупреждение.
	 */
	case WARNING = 'warning';

	/**
	 * Информационное сообщение.
	 */
	case INFO = 'info';
}
