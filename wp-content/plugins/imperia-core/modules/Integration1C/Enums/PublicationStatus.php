<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Enums;

/**
 * ==========================================================================
 * PUBLICATION STATUS
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Определяет состояние публикации товара
 * в доменной модели Integration1C.
 *
 * Перечисление описывает только состояние публикации
 * и не зависит от реализации WordPress или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 *
 * - определяет допустимые состояния публикации товара;
 * - обеспечивает типобезопасность;
 * - исключает использование строковых литералов.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 *
 * - публикацию товара;
 * - запись данных в WordPress;
 * - преобразование статусов WordPress;
 * - бизнес-логику обмена.
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 *
 * Используется объектами предметной области,
 * которым необходимо определить состояние публикации товара.
 */
enum PublicationStatus: string
{
	/**
	 * Товар опубликован.
	 */
	case PUBLISHED = 'published';

	/**
	 * Товар сохранён как черновик.
	 */
	case DRAFT = 'draft';
}
