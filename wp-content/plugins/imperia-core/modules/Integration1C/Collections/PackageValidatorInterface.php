<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Contracts;

use Imperia\Modules\Integration1C\Models\ExchangePackage;
use Imperia\Modules\Integration1C\Models\PackageValidationResult;

/**
 * ==========================================================================
 * PACKAGE VALIDATOR INTERFACE
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Определяет контракт валидатора пакета обмена.
 *
 * Валидатор отвечает за проверку содержимого
 * пакета обмена и возвращает результат проверки.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 *
 * • проверка пакета обмена;
 * • возврат результата проверки.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 *
 * • изменение пакета обмена;
 * • сохранение данных;
 * • импорт товаров;
 * • отображение ошибок;
 * • логирование.
 *
 * --------------------------------------------------------------------------
 * Особенности
 * --------------------------------------------------------------------------
 *
 * Любая реализация интерфейса должна:
 *
 * • принимать готовый ExchangePackage;
 * • не изменять его содержимое;
 * • возвращать новый PackageValidationResult.
 */
interface PackageValidatorInterface
{
	/**
	 * Выполняет проверку пакета обмена.
	 *
	 * @param ExchangePackage $package
	 * Пакет обмена для проверки.
	 *
	 * @return PackageValidationResult
	 * Результат проверки.
	 */
	public function validate(
		ExchangePackage $package
	): PackageValidationResult;
}
