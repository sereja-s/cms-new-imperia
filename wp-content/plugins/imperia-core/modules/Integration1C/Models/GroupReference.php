<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Models;

use Imperia\Modules\Integration1C\Contracts\ModelInterface;
use Imperia\Modules\Integration1C\ValueObjects\GroupName;
use Imperia\Modules\Integration1C\ValueObjects\GroupUuid;

/**
 * ==========================================================================
 * GROUP REFERENCE
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет ссылку на группу товаров,
 * полученную из информационной системы 1С.
 *
 * Модель объединяет технический идентификатор группы
 * и её название в единую предметную сущность.
 *
 * Используется сервисами подготовки обмена
 * и согласования групп 1С с категориями WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Что хранит модель
 * --------------------------------------------------------------------------
 *
 * • уникальный идентификатор группы 1С;
 * • название группы.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 *
 * • хранение данных группы;
 * • предоставление доступа к данным группы;
 * • сравнение двух объектов группы.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 *
 * • поиск категории WooCommerce;
 * • сопоставление группы и категории;
 * • проверку существования категории;
 * • создание категории;
 * • изменение названия группы;
 * • сохранение данных;
 * • обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 *
 * • всегда содержит корректный GroupUuid;
 * • всегда содержит корректный GroupName;
 * • после создания объект не изменяется (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 *
 * Создаётся при чтении данных обмена из 1С
 * и сопровождает данные группы
 * на протяжении всего процесса синхронизации.
 */
final class GroupReference implements ModelInterface
{
	/**
	 * Уникальный идентификатор группы.
	 */
	private GroupUuid $groupUuid;


	/**
	 * Название группы.
	 */
	private GroupName $groupName;


	/**
	 * Создаёт модель группы товаров.
	 *
	 * @param GroupUuid $groupUuid Уникальный идентификатор группы.
	 * @param GroupName $groupName Название группы.
	 */
	public function __construct(
		GroupUuid $groupUuid,
		GroupName $groupName
	) {
		$this->groupUuid = $groupUuid;
		$this->groupName = $groupName;
	}


	/**
	 * Возвращает уникальный идентификатор группы.
	 *
	 * @return GroupUuid
	 */
	public function groupUuid(): GroupUuid
	{
		return $this->groupUuid;
	}


	/**
	 * Возвращает название группы.
	 *
	 * @return GroupName
	 */
	public function groupName(): GroupName
	{
		return $this->groupName;
	}


	/**
	 * Сравнивает две модели группы.
	 *
	 * Две группы считаются одинаковыми,
	 * если совпадают их идентификатор
	 * и название.
	 *
	 * @param GroupReference $other
	 *
	 * @return bool
	 */
	public function equals(GroupReference $other): bool
	{
		return
			$this->groupUuid->equals($other->groupUuid())
			&&
			$this->groupName->equals($other->groupName());
	}


	/**
	 * Проверяет,
	 * является ли группа тем же объектом.
	 *
	 * Сравнение выполняется
	 * по уникальному идентификатору 1С.
	 *
	 * Название группы может изменяться.
	 *
	 * @param GroupReference $other
	 *
	 * @return bool
	 */
	public function sameIdentity(GroupReference $other): bool
	{
		return $this->groupUuid->equals(
			$other->groupUuid()
		);
	}
}
