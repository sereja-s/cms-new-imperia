<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Models;

use Imperia\Modules\Integration1C\Contracts\ModelInterface;
use Imperia\Modules\Integration1C\ValueObjects\ImageOrder;
use Imperia\Modules\Integration1C\ValueObjects\ImageSource;

/**
 * ==========================================================================
 * PRODUCT IMAGE
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет одно изображение товара,
 * полученное из информационной системы 1С.
 *
 * Данная модель является частью ProductCard
 * и используется исключительно внутри процесса обмена.
 *
 * --------------------------------------------------------------------------
 * Что хранит модель
 * --------------------------------------------------------------------------
 *
 * • источник изображения;
 * • порядковый номер изображения.
 *
 * --------------------------------------------------------------------------
 * Что НЕ хранит модель
 * --------------------------------------------------------------------------
 *
 * Данная модель не содержит:
 *
 * • ALT изображения;
 * • URL сайта;
 * • attachment ID WordPress;
 * • MIME-тип;
 * • размеры изображения;
 * • статус главного изображения.
 *
 * --------------------------------------------------------------------------
 * Почему отсутствует ALT
 * --------------------------------------------------------------------------
 *
 * ALT формируется автоматически
 * сервисом загрузки изображений
 * по шаблону:
 *
 *     {product_name} — фото {number}
 *
 * Таким образом сохраняется единый
 * стиль оформления изображений,
 * а модуль не зависит от качества
 * заполнения данных в 1С.
 *
 * --------------------------------------------------------------------------
 * Главное изображение
 * --------------------------------------------------------------------------
 *
 * Главное изображение определяется
 * объектом ImageOrder.
 *
 * Изображение с порядковым номером "1"
 * считается главным изображением товара.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 *
 * • хранение данных изображения;
 * • предоставление доступа к данным;
 * • сравнение двух объектов изображения.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 *
 * • загрузку изображения;
 * • получение файла;
 * • генерацию ALT;
 * • назначение изображения товару;
 * • сохранение данных;
 * • обмен с 1С или WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 *
 * • всегда содержит корректный ImageSource;
 * • всегда содержит корректный ImageOrder;
 * • после создания объект не изменяется (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 *
 * Создаётся при построении ProductCard
 * и сопровождает изображение товара
 * на протяжении всего процесса обмена.
 */
final class ProductImage implements ModelInterface
{
	/**
	 * Источник изображения.
	 */
	private ImageSource $imageSource;


	/**
	 * Порядковый номер изображения.
	 */
	private ImageOrder $imageOrder;


	/**
	 * Создаёт модель изображения товара.
	 *
	 * @param ImageSource $imageSource Источник изображения.
	 * @param ImageOrder  $imageOrder  Порядковый номер изображения.
	 */
	public function __construct(
		ImageSource $imageSource,
		ImageOrder $imageOrder
	) {
		$this->imageSource = $imageSource;
		$this->imageOrder  = $imageOrder;
	}


	/**
	 * Возвращает источник изображения.
	 *
	 * @return ImageSource
	 */
	public function imageSource(): ImageSource
	{
		return $this->imageSource;
	}


	/**
	 * Возвращает порядковый номер изображения.
	 *
	 * @return ImageOrder
	 */
	public function imageOrder(): ImageOrder
	{
		return $this->imageOrder;
	}


	/**
	 * Проверяет,
	 * является ли изображение главным.
	 *
	 * Главное изображение имеет порядок 1.
	 *
	 * Метод является вспомогательным
	 * и делегирует проверку объекту ImageOrder.
	 *
	 * @return bool
	 */
	public function isPrimary(): bool
	{
		return $this->imageOrder->isPrimary();
	}


	/**
	 * Сравнивает два объекта изображения.
	 *
	 * Два изображения считаются одинаковыми,
	 * если совпадают их источник
	 * и порядковый номер.
	 *
	 * @param ProductImage $other
	 *
	 * @return bool
	 */
	public function equals(ProductImage $other): bool
	{
		return
			$this->imageSource->equals($other->imageSource())
			&&
			$this->imageOrder->equals($other->imageOrder());
	}
}
