<?php

declare(strict_types=1);

namespace Imperia\Modules\Integration1C\Models;

use Imperia\Modules\Integration1C\Collections\ProductCollection;
use Imperia\Modules\Integration1C\Contracts\ModelInterface;

/**
 * ==========================================================================
 * EXCHANGE PACKAGE
 * ==========================================================================
 *
 * Назначение
 * --------------------------------------------------------------------------
 * Представляет пакет обмена,
 * полученный из информационной системы 1С.
 *
 * Пакет обмена объединяет карточки товаров,
 * предназначенные для обработки
 * в рамках одного обмена.
 *
 * --------------------------------------------------------------------------
 * Что хранит модель
 * --------------------------------------------------------------------------
 *
 * • коллекцию товаров.
 *
 * --------------------------------------------------------------------------
 * Ответственность
 * --------------------------------------------------------------------------
 *
 * • хранение коллекции товаров;
 * • предоставление доступа к товарам;
 * • сравнение пакетов обмена.
 *
 * --------------------------------------------------------------------------
 * Не отвечает за
 * --------------------------------------------------------------------------
 *
 * • чтение XML;
 * • импорт товаров;
 * • согласование категорий;
 * • сохранение данных;
 * • обмен с WooCommerce.
 *
 * --------------------------------------------------------------------------
 * Инварианты
 * --------------------------------------------------------------------------
 *
 * • всегда содержит корректную ProductCollection;
 * • после создания объект не изменяется (Immutable).
 *
 * --------------------------------------------------------------------------
 * Жизненный цикл
 * --------------------------------------------------------------------------
 *
 * Создаётся после разбора данных обмена
 * и сопровождает пакет
 * до завершения синхронизации.
 */
final class ExchangePackage implements ModelInterface
{
	/**
	 * Коллекция товаров.
	 */
	private ProductCollection $products;


	/**
	 * Создаёт пакет обмена.
	 *
	 * @param ProductCollection $products Коллекция товаров.
	 */
	public function __construct(
		ProductCollection $products
	) {
		$this->products = $products;
	}


	/**
	 * Возвращает коллекцию товаров.
	 */
	public function products(): ProductCollection
	{
		return $this->products;
	}


	/**
	 * Проверяет,
	 * пуст ли пакет обмена.
	 */
	public function isEmpty(): bool
	{
		return $this->products->isEmpty();
	}


	/**
	 * Возвращает количество товаров.
	 */
	public function count(): int
	{
		return $this->products->count();
	}


	/**
	 * Сравнивает два пакета обмена.
	 */
	public function equals(
		ExchangePackage $other
	): bool {

		return
			$this->products->equals(
				$other->products()
			);
	}
}
